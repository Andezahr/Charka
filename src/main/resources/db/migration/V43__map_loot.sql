-- KF-05: предмет на карте идущего боя — мастер кладёт строку справочника системы, персонаж рядом подбирает в носимый инвентарь.
-- Кончился бой — предметы с карты уходят вместе с ним
CREATE TABLE map_loot
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT       NOT NULL REFERENCES encounter (id) ON DELETE CASCADE,
    pos_x        INT          NOT NULL,
    pos_y        INT          NOT NULL,
    pos_level    INT          NOT NULL DEFAULT 0,
    catalog_key  VARCHAR(128) NOT NULL,
    name         VARCHAR(255) NOT NULL,
    quantity     INT          NOT NULL DEFAULT 1
);
