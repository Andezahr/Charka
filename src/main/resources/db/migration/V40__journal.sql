-- J-01: журнал боя — одна запись на действие: итог, фишки, расчёт. Броски действия сворачиваются в неё
CREATE TABLE journal_entry
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT        NOT NULL REFERENCES campaign (id) ON DELETE CASCADE,
    character_id BIGINT REFERENCES character (id) ON DELETE SET NULL,
    kind         VARCHAR(20)   NOT NULL,
    title        VARCHAR(300)  NOT NULL,
    outcome      VARCHAR(1000),
    success      BOOLEAN,
    total        INTEGER,
    difficulty   INTEGER,
    chips        VARCHAR(2000),
    steps        TEXT,
    hidden       BOOLEAN DEFAULT FALSE NOT NULL,
    game_date    DATE,
    created_at   TIMESTAMP     NOT NULL
);

CREATE INDEX idx_journal_campaign ON journal_entry (campaign_id, created_at);

ALTER TABLE roll_log ADD COLUMN journal_entry_id BIGINT;
