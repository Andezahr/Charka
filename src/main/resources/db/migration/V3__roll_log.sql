-- D-02: лог бросков кубиков. Удаление кампании удаляет её броски, удаление персонажа оставляет бросок без автора.
CREATE TABLE roll_log
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT REFERENCES campaign (id) ON DELETE CASCADE,
    character_id BIGINT REFERENCES character (id) ON DELETE SET NULL,
    expression   VARCHAR(64)   NOT NULL,
    details      VARCHAR(1000) NOT NULL,
    total        INTEGER       NOT NULL,
    label        VARCHAR(255),
    game_date    DATE,
    created_at   TIMESTAMP     NOT NULL
);

CREATE INDEX idx_roll_log_campaign ON roll_log (campaign_id, created_at);
CREATE INDEX idx_roll_log_character ON roll_log (character_id, created_at);
