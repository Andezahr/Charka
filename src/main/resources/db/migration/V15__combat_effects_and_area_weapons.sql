-- Что длится на участнике боя несколько раундов: удаляется вместе с участником
CREATE TABLE combat_effect
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_id BIGINT       NOT NULL REFERENCES encounter_participant (id) ON DELETE CASCADE,
    label          VARCHAR(255) NOT NULL,
    rounds_left    INTEGER      NOT NULL,
    damage         VARCHAR(255),
    attack_option  VARCHAR(64)
);

CREATE TABLE combat_effect_data
(
    effect_id  BIGINT      NOT NULL REFERENCES combat_effect (id) ON DELETE CASCADE,
    data_key   VARCHAR(64) NOT NULL,
    data_value VARCHAR(255),
    PRIMARY KEY (effect_id, data_key)
);

