-- A-06: заготовка боя (сцена): карта, кто из NPC выходит, кто в засаде. Начинается одним нажатием, после боя остаётся
CREATE TABLE scene
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   BIGINT       NOT NULL REFERENCES campaign (id) ON DELETE CASCADE,
    name          VARCHAR(100) NOT NULL,
    battle_map_id BIGINT       REFERENCES battle_map (id) ON DELETE SET NULL,
    with_players  BOOLEAN      DEFAULT TRUE NOT NULL,
    group_players BOOLEAN      DEFAULT FALSE NOT NULL,
    group_npcs    BOOLEAN      DEFAULT FALSE NOT NULL
);
CREATE INDEX scene_campaign ON scene (campaign_id);

-- NPC сцены: по шаблону системы (создаются при начале) или уже существующий персонаж кампании
CREATE TABLE scene_npc
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scene_id      BIGINT       NOT NULL REFERENCES scene (id) ON DELETE CASCADE,
    template_code VARCHAR(64),
    character_id  BIGINT       REFERENCES character (id) ON DELETE CASCADE,
    name          VARCHAR(100),
    npc_count     INT          DEFAULT 1 NOT NULL,
    advanced      BOOLEAN      DEFAULT FALSE NOT NULL,
    ambush        BOOLEAN      DEFAULT FALSE NOT NULL
);
CREATE INDEX scene_npc_scene ON scene_npc (scene_id);
