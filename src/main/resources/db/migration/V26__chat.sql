-- U-06: чат кампании. В ленте вперемешку с бросками (roll_log), в экспорт не входит, как и лог бросков
CREATE TABLE chat_message
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT        NOT NULL REFERENCES campaign (id) ON DELETE CASCADE,
    character_id BIGINT        REFERENCES character (id) ON DELETE SET NULL,
    author       VARCHAR(100)  NOT NULL,
    text         VARCHAR(500)  NOT NULL,
    game_date    DATE,
    created_at   TIMESTAMP     NOT NULL
);
CREATE INDEX chat_message_campaign ON chat_message (campaign_id, created_at);
