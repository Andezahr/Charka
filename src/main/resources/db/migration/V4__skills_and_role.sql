-- K-01, K-03: навыки персонажа и его роль/класс. Коды навыков и ролей задаёт игровая система.
ALTER TABLE character ADD COLUMN role_code VARCHAR(64);

CREATE TABLE character_skill
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT      NOT NULL REFERENCES character (id) ON DELETE CASCADE,
    skill_code   VARCHAR(64) NOT NULL,
    skill_level  INTEGER     NOT NULL,
    custom_name  VARCHAR(255)
);

CREATE INDEX idx_character_skill_character ON character_skill (character_id);
