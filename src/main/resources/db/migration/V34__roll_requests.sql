-- A-07, A-08: мастер просит бросок у игрока (или у нескольких сразу — group_key общий). Открыт, пока не брошен
CREATE TABLE roll_request
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT       NOT NULL REFERENCES campaign (id) ON DELETE CASCADE,
    character_id BIGINT       NOT NULL REFERENCES character (id) ON DELETE CASCADE,
    kind         VARCHAR(16)  NOT NULL,
    code         VARCHAR(64)  NOT NULL,
    label        VARCHAR(255) NOT NULL,
    difficulty   INT,
    group_key    VARCHAR(32),
    created_at   TIMESTAMP    NOT NULL,
    done_at      TIMESTAMP,
    success      BOOLEAN,
    total        INT,
    result       VARCHAR(500)
);
CREATE INDEX roll_request_campaign ON roll_request (campaign_id, done_at);
