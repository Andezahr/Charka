-- A-01: отмена последнего действия. Снимок игрового состояния кампании до действия (строки таблиц с прежними id, JSON)
CREATE TABLE undo_entry
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT       NOT NULL REFERENCES campaign (id) ON DELETE CASCADE,
    user_id      BIGINT       REFERENCES app_user (id) ON DELETE SET NULL,
    character_id BIGINT       REFERENCES character (id) ON DELETE SET NULL,
    label        VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    snapshot     TEXT         NOT NULL
);
CREATE INDEX undo_entry_campaign ON undo_entry (campaign_id, id);
