-- Идущий бой кампании. Закончился — строки удаляются: броски остаются в логе
CREATE TABLE encounter
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  BIGINT  NOT NULL UNIQUE REFERENCES campaign (id) ON DELETE CASCADE,
    round_number INTEGER NOT NULL
);

CREATE TABLE encounter_participant
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id       BIGINT       NOT NULL REFERENCES encounter (id) ON DELETE CASCADE,
    character_id       BIGINT       NOT NULL REFERENCES character (id) ON DELETE CASCADE,
    initiative         INTEGER      NOT NULL,
    initiative_details VARCHAR(255),
    turn_order         INTEGER      NOT NULL,
    done               BOOLEAN      NOT NULL,
    waiting            BOOLEAN      NOT NULL,
    UNIQUE (encounter_id, character_id)
);
