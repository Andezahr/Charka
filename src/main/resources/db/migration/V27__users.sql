-- U-03: пользователи. Мастер кампании видит всё в ней, игрок — своих персонажей.
-- У старых кампаний мастера нет: им становится первый зарегистрированный (UserService.register)
CREATE TABLE app_user
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(32)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP    NOT NULL
);

ALTER TABLE campaign ADD COLUMN gm_user_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL;
ALTER TABLE character ADD COLUMN player_user_id BIGINT REFERENCES app_user (id) ON DELETE SET NULL;
