CREATE TABLE pending_blast
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id BIGINT NOT NULL REFERENCES character (id) ON DELETE CASCADE,
    weapon       VARCHAR(255),
    expression   VARCHAR(255),
    amount       INTEGER NOT NULL,
    radius       INTEGER NOT NULL,
    note         VARCHAR(1000)
);

CREATE TABLE pending_blast_data
(
    blast_id   BIGINT       NOT NULL REFERENCES pending_blast (id) ON DELETE CASCADE,
    data_key   VARCHAR(64)  NOT NULL,
    data_value VARCHAR(255),
    PRIMARY KEY (blast_id, data_key)
);

CREATE TABLE pending_blast_target
(
    blast_id     BIGINT NOT NULL REFERENCES pending_blast (id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL,
    PRIMARY KEY (blast_id, character_id)
);
